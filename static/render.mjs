// Renders static/*.tsx pages to self-contained HTML fragments in static/dist/,
// for sites that can't run React (publicai.network on Jekyll). Each fragment
// carries its own <style> and is wrapped in Liquid raw tags, so Jekyll's
// {% include_relative %} drops it in unchanged. Also renders the social
// card, static/dist/card.png (see card.mjs).
//
//   npm install && npm run static
/* global console */
import { build } from "esbuild";
import { mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { renderCard } from "./card.mjs";

const here = import.meta.dirname;
const dist = path.join(here, "dist");
const tmp = path.join(here, ".tmp");
const css = await readFile(path.join(here, "..", "react", "progress.css"), "utf8");
const data = JSON.parse(await readFile(path.join(here, "..", "data", "progress.json"), "utf8"));

const pages = (await readdir(here)).filter((f) => f.endsWith(".tsx"));
await mkdir(dist, { recursive: true });
for (const page of pages) {
  const name = page.replace(/\.tsx$/, "");
  const out = path.join(tmp, `${name}.mjs`);
  await build({
    entryPoints: [path.join(here, page)],
    outfile: out,
    bundle: true,
    format: "esm",
    platform: "node",
    jsx: "automatic",
    packages: "external",
    logLevel: "warning",
  });
  const { default: Page } = await import(pathToFileURL(out).href);
  const { renderToStaticMarkup } = await import("react-dom/server");
  const { createElement } = await import("react");
  const html = renderToStaticMarkup(createElement(Page));
  const fragment = [
    `<!-- Generated by forpublicai/progress static/render.mjs from ${page}, data as of ${data.asOf}. Do not edit. -->`,
    "{% raw %}",
    `<style>\n${css.trim()}\n</style>`,
    html,
    "{% endraw %}",
    "",
  ].join("\n");
  await writeFile(path.join(dist, `${name}.html`), fragment);
  console.log(`static/dist/${name}.html  ${(fragment.length / 1024).toFixed(1)} kB`);
}
await rm(tmp, { recursive: true, force: true });
await renderCard(data, path.join(dist, "card.png"));
